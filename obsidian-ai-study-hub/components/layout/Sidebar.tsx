"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";

const links = [
  { href: "/", label: "Dashboard", icon: HomeIcon },
  { href: "/notes", label: "Notes", icon: FileIcon },
  { href: "/flashcards", label: "Flashcards", icon: CardIcon },
  { href: "/quizzes", label: "Quizzes", icon: ClipboardIcon },
  { href: "/import", label: "Import", icon: UploadIcon },
  { href: "/search", label: "Search", icon: SearchIcon },
];

export default function Sidebar() {
  const pathname = usePathname();

  return (
    <aside className="fixed inset-y-0 left-0 w-64 bg-surface-900 border-r border-surface-800 hidden lg:flex flex-col z-30">
      <div className="p-4 border-b border-surface-800">
        <Link href="/" className="flex items-center gap-2 text-white font-semibold text-lg">
          <BookOpenIcon />
          <span>Study Hub</span>
        </Link>
      </div>
      <nav className="flex-1 p-3 space-y-1 overflow-y-auto">
        {links.map((link) => {
          const isActive = pathname === link.href || (link.href !== "/" && pathname.startsWith(link.href));
          return (
            <Link
              key={link.href}
              href={link.href}
              className={`flex items-center gap-3 px-3 py-2 rounded-lg text-sm font-medium transition-colors ${
                isActive
                  ? "bg-accent-600/20 text-accent-400"
                  : "text-slate-400 hover:text-white hover:bg-surface-800"
              }`}
            >
              <link.icon />
              {link.label}
            </Link>
          );
        })}
      </nav>
    </aside>
  );
}

